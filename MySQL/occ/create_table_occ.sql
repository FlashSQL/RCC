CREATE DATABASE IF NOT EXISTS occbench;
USE occbench;

DROP TABLE IF EXISTS kv;
DROP TABLE IF EXISTS global_tid;

CREATE TABLE kv (
  id     BIGINT PRIMARY KEY,
  v      BIGINT NOT NULL,
  tid    BIGINT NOT NULL,
  is_hot TINYINT NOT NULL DEFAULT 0,
  pad    VARBINARY(2048) NOT NULL 
) ENGINE=InnoDB;

CREATE TABLE global_tid (
  k   TINYINT PRIMARY KEY,
  tid BIGINT NOT NULL
) ENGINE=InnoDB;

INSERT INTO global_tid(k, tid) VALUES (1, 0)
  ON DUPLICATE KEY UPDATE tid = VALUES(tid);


DROP TABLE IF EXISTS nums_10000;
CREATE TABLE nums_10000 (n INT PRIMARY KEY) ENGINE=InnoDB;

INSERT INTO nums_10000(n)
SELECT a.n + 10*b.n + 100*c.n + 1000*d.n AS n
FROM (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
      UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) a
CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
      UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) b
CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
      UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) c
CROSS JOIN (SELECT 0 n UNION ALL SELECT 1 UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4
      UNION ALL SELECT 5 UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9) d;

DELIMITER $$

DROP PROCEDURE IF EXISTS populate_kv_big $$
CREATE PROCEDURE populate_kv_big(IN pN BIGINT, IN pH BIGINT, IN pPadBytes INT)
BEGIN
  DECLARE base BIGINT DEFAULT 0;
  DECLARE batch BIGINT DEFAULT 10000;

  SET @old_uniq = @@unique_checks;
  SET @old_fk   = @@foreign_key_checks;
  SET unique_checks = 0;
  SET foreign_key_checks = 0;

  TRUNCATE TABLE kv;

  WHILE base < pN DO
    INSERT INTO kv (id, v, tid, is_hot, pad)
    SELECT
      base + n + 1 AS id,
      0 AS v,
      0 AS tid,
      CASE WHEN (base + n + 1) <= pH THEN 1 ELSE 0 END AS is_hot,
      REPEAT(0x78, pPadBytes) AS pad     
    FROM nums_10000
    WHERE base + n < pN;

    SET base = base + batch;
  END WHILE;

  SET unique_checks = @old_uniq;
  SET foreign_key_checks = @old_fk;
END $$

DELIMITER ;


CALL populate_kv_big(12800000, 100, 2048);

